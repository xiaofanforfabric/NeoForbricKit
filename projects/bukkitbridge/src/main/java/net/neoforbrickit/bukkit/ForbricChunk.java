/*
 * Forbric Bukkit bridge — a Bukkit Chunk backed by a Minecraft LevelChunk.
 */
package net.neoforbrickit.bukkit;

/**
 * One loaded chunk, as a plugin sees it: a handle over a Minecraft {@code LevelChunk}.
 *
 * <p><b>What this is for.</b> A pre-generator is the plugin that made this necessary — Chunky asks
 * {@code World.getChunkAtAsync} for every coordinate in its region and, once each future completes, asks
 * {@code Chunk.isGenerated} to decide whether the chunk is real. Without a {@code Chunk} to hand back the
 * future could never complete with anything a caller could use, and without {@code getChunkAt} there would be
 * nothing to complete it with, so the two are one piece of work rather than two.
 *
 * <p><b>A handle, not a snapshot.</b> The game's chunks are mutable and live in memory while loaded, so this
 * class holds the {@code LevelChunk} and reads through it. A {@code ChunkSnapshot} is the API's answer to
 * "give me something that cannot change", and it is a different, much larger method — see
 * {@link #getChunkSnapshot}.
 *
 * <h2>Loaded versus generated</h2>
 *
 * <p>The two questions are not the same and both are answered from the game's own state:
 *
 * <ul>
 *   <li><b>Generated</b> — does this chunk exist on disk. Answered from the chunk source's
 *       {@code hasChunk}, which is true for a chunk that exists whether or not anyone is holding it.
 *       This is the one Chunky needs: it decides whether a coordinate still has to be generated.</li>
 *   <li><b>Loaded</b> — is this chunk in memory right now. Answered by whether the wrapper has a game chunk
 *       at all, which is exactly the state the API is asking about.</li>
 * </ul>
 *
 * <p>A chunk that is generated but not loaded is the normal case for a pre-generator and the reason the two
 * cannot be collapsed into one answer.
 *
 * <h2>What a read here is allowed to do</h2>
 *
 * <p>Nothing in this class loads a chunk. A block read or a snapshot is a question, and on a render thread a
 * question that loads is a hang: the load is finished by the thread the caller is waiting on. So a chunk that
 * is not in memory answers air to {@code getBlock}, and its snapshot comes out of the region file without a
 * load -- see {@code ForbricChunkSnapshot#read}.
 */
final class ForbricChunk implements org.bukkit.Chunk {

	/**
	 * The game's chunk, or null when this chunk is generated but not loaded.
	 *
	 * <p>Nullable rather than absent because the API has a state for it: a chunk a pre-generator has just
	 * written is generated and is not in memory, and a plugin asking about it must get an object it can call
	 * {@link #isGenerated()} on rather than a null it has to check for itself.
	 */
	private final net.minecraft.world.level.chunk.LevelChunk handle;

	private final ForbricWorld world;
	private final int x;
	private final int z;

	ForbricChunk(ForbricWorld world, net.minecraft.world.level.chunk.LevelChunk handle, int x, int z) {
		this.world = world;
		this.handle = handle;
		this.x = x;
		this.z = z;
	}

	/** Wraps a chunk that is in memory. */
	static ForbricChunk loaded(ForbricWorld world, net.minecraft.world.level.chunk.LevelChunk handle) {
		return new ForbricChunk(world, handle, handle.getPos().x(), handle.getPos().z());
	}

	/** Wraps a chunk that exists but is not in memory, for the coordinate its caller asked about. */
	static ForbricChunk unloaded(ForbricWorld world, int x, int z) {
		return new ForbricChunk(world, null, x, z);
	}

	@Override
	public int getX() {
		return x;
	}

	@Override
	public int getZ() {
		return z;
	}

	@Override
	public org.bukkit.World getWorld() {
		return world;
	}

	/**
	 * Whether this chunk exists on disk.
	 *
	 * <p>Asked of the save itself -- the region file's own index -- rather than of the chunk source's
	 * {@code hasChunk}, which answers "is it in memory". The two differ in exactly the case this is used for:
	 * a chunk a pre-generator has just written is generated and no longer loaded.
	 *
	 * <p>They differ in the case that matters more, too. A freshly started server holds no chunks, so a
	 * renderer asking "is there anything in this dimension" got {@code false} for every coordinate it tried
	 * and concluded the world was empty. Nothing is loaded or generated to answer this.
	 */
	@Override
	public boolean isGenerated() {
		return world.isChunkGenerated(x, z);
	}

	@Override
	public boolean isLoaded() {
		return handle != null;
	}

	@Override
	public boolean load() {
		return load(true);
	}

	@Override
	public boolean load(boolean generate) {
		// getChunkAt returns the chunk whether it was generated by this call or already there, so the boolean
		// this bridge has to produce is "is it loaded now", not "did this call create it". A plugin that wants
		// to know whether the chunk was new asks isGenerated() first.
		return world.getChunkAt(x, z, generate) != null;
	}

	@Override
	public boolean isForceLoaded() {
		return world.isChunkForceLoaded(x, z);
	}

	@Override
	public void setForceLoaded(boolean force) {
		world.setChunkForceLoaded(x, z, force);
	}

	@Override
	public boolean addPluginChunkTicket(org.bukkit.plugin.Plugin plugin) {
		return world.addPluginChunkTicket(x, z, plugin);
	}

	@Override
	public boolean removePluginChunkTicket(org.bukkit.plugin.Plugin plugin) {
		return world.removePluginChunkTicket(x, z, plugin);
	}

	@Override
	public java.util.Collection<org.bukkit.plugin.Plugin> getPluginChunkTickets() {
		return world.pluginChunkTickets(x, z);
	}

	@Override
	public org.bukkit.block.Block getBlock(int bx, int by, int bz) {
		// Deliberately through the world rather than through the wrapper's own handle: a block is addressed by
		// world coordinates, and a chunk-local offset would be a second way of locating the same block that
		// could disagree with the first after a chunk is reloaded.
		return world.getBlockAt((x << 4) + bx, by, (z << 4) + bz, handle != null);
	}

	@Override
	public org.bukkit.ChunkSnapshot getChunkSnapshot(boolean includeMaxBlockY, boolean includeBiome,
					boolean includeBiomeTempRain, boolean includeLightData) {
		// A loaded chunk is copied from memory; one that is not is read out of its region file. Both are
		// full answers, and neither loads anything.
		//
		// The file path is the one a renderer takes: BlueMap snapshots the chunks of a world that is not
		// ticking them, from its own thread, where a load would wait on the thread that is doing the asking.
		// Refusing here -- which is what this used to do -- left the renderer with something it could not
		// tell from an empty chunk, and that is a blank map with nothing in any log.
		if (handle != null) {
			return new ForbricChunkSnapshot(world, handle, includeMaxBlockY);
		}
		org.bukkit.ChunkSnapshot fromDisk = ForbricChunkSnapshot.read(world, x, z);
		if (fromDisk != null) {
			return fromDisk;
		}
		// Nothing saved at this coordinate and nothing in memory: a chunk of air is the honest answer, and
		// it is what the API's own implementation gives for a coordinate outside the generated world.
		return world.getEmptyChunkSnapshot(x, z, includeBiome, includeBiomeTempRain);
	}

	@Override
	public boolean isEntitiesLoaded() {
		throw notYet("isEntitiesLoaded");
	}

	@Override
	public org.bukkit.entity.Entity[] getEntities() {
		throw notYet("getEntities");
	}

	@Override
	public org.bukkit.block.BlockState[] getTileEntities(boolean useSnapshot) {
		throw notYet("getTileEntities");
	}

	@Override
	public java.util.Collection<org.bukkit.block.BlockState> getTileEntities(
					java.util.function.Predicate<? super org.bukkit.block.Block> filter, boolean useSnapshot) {
		throw notYet("getTileEntities");
	}

	@Override
	public boolean unload() {
		return unload(true);
	}

	@Override
	public boolean unload(boolean save) {
		throw notYet("unload");
	}

	@Override
	public boolean isSlimeChunk() {
		throw notYet("isSlimeChunk");
	}

	@Override
	public long getInhabitedTime() {
		throw notYet("getInhabitedTime");
	}

	@Override
	public void setInhabitedTime(long inhabitedTime) {
		throw notYet("setInhabitedTime");
	}

	@Override
	public boolean contains(org.bukkit.block.data.BlockData block) {
		throw notYet("contains");
	}

	@Override
	public boolean contains(org.bukkit.block.Biome biome) {
		throw notYet("contains");
	}

	@Override
	public org.bukkit.Chunk.LoadLevel getLoadLevel() {
		throw notYet("getLoadLevel");
	}

	@Override
	public java.util.Collection<org.bukkit.generator.structure.GeneratedStructure> getStructures() {
		throw notYet("getStructures");
	}

	@Override
	public java.util.Collection<org.bukkit.generator.structure.GeneratedStructure> getStructures(
					org.bukkit.generator.structure.Structure structure) {
		throw notYet("getStructures");
	}

	@Override
	public java.util.Collection<org.bukkit.entity.Player> getPlayersSeeingChunk() {
		throw notYet("getPlayersSeeingChunk");
	}

	@Override
	public org.bukkit.persistence.PersistentDataContainer getPersistentDataContainer() {
		throw notYet("getPersistentDataContainer");
	}

	private static UnsupportedOperationException notYet(String what) {
		return new UnsupportedOperationException(
						"[Forbric/Bukkit] Chunk." + what + "() is not implemented by this bridge yet");
	}
}
